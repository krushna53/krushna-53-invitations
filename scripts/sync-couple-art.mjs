// Lists the couple pictures in public/art/couples and writes lib/couple-art.js,
// so a design appears as soon as its picture (JPG, PNG or WebP) (file name = design id) is dropped in.
// Runs automatically before `npm run dev` and `npm run build`.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "public", "art", "couples");
const files = {};
if (fs.existsSync(dir))
  for (const f of fs.readdirSync(dir).sort())
    if (/\.(jpe?g|png|webp)$/i.test(f) && !f.startsWith(".")) files[f.replace(/(\.(jpe?g|png|webp))+$/i, "").toLowerCase()] ??= f; // "x.png.png" (hidden extensions on Windows) still maps to "x"
const ids = Object.keys(files);
const out = `// Generated by scripts/sync-couple-art.mjs — do not edit by hand.
// Couple pictures found in public/art/couples (file name = design id).
export const COUPLE_ART_FILES = ${JSON.stringify(files, null, 2)};
export const COUPLE_ART_READY = Object.keys(COUPLE_ART_FILES);
`;
fs.writeFileSync(path.join(process.cwd(), "lib", "couple-art.js"), out);
console.log(`couple art: ${ids.length ? ids.join(", ") : "none yet"}`);
